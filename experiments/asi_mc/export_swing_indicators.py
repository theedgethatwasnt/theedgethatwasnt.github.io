#!/usr/bin/env python3
"""
Export Swing Structure Indicators to parquet.
==============================================
Extends ASI-MC indicator parquets with swing structure columns using the
SAME SwingStructure class from lib/indicators.py that runs in the live curator.

This guarantees training and live data are generated by identical code —
the same guarantee that already exists for ASI-MC (lib/asi_indicator.py) and ER_norm.

New columns added to existing parquets:
  sb_a       — ASI structural breakout state {-1,-0.5,0,+0.5,+1}
  erp_a      — Extended Range Position on ASI (unclamped continuous)
  hh_asi     — higher_highs binary {0.0, 1.0} on ASI TopsBots swings
  hl_asi     — higher_lows  binary {0.0, 1.0} on ASI TopsBots swings
  erp_p      — Extended Range Position on price (unclamped continuous)
  hh_price   — higher_highs binary {0.0, 1.0} on price TopsBots swings
  hl_price   — higher_lows  binary {0.0, 1.0} on price TopsBots swings

Experiment input mappings:
  V3: mc_d_a, mc_dd_a, er_norm, UPnL (4 inputs)
  E1: mc_d_a, mc_dd_a, er_norm, sb_a, erp_p, UPnL (6 inputs)
  E2: mc_d_a, mc_dd_a, er_norm, sb_a, hh_asi, hl_asi, UPnL (7 inputs)
  E3: mc_d_a, mc_dd_a, er_norm, erp_a, hh_asi, hl_asi, erp_p, UPnL (8 inputs)

Curator-identical guarantee:
  lib/indicators.py:SwingStructure.append_m5() + .compute() is called for
  every M5 bar in sequence — the same call pattern as the live curator.
  compute_all_swing_features() from lib/swing_indicators.py is the shared
  batch computation used by both.

Usage (on Hetzner with S5 parquets):
  ASI_MC_DATA_DIR=/root/neat/data python3 export_swing_indicators.py

Usage (local, if scalper_parquet available):
  python3 research/experiments/asi_mc/export_swing_indicators.py
"""

import sys
import os
import gc
import time
import numpy as np
import pandas as pd
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(PROJECT_ROOT))

from lib.indicators import SwingStructure
from lib.swing_indicators import compute_ic, compute_corr
from lib.pair_config import ALL_PAIR_NAMES

S5_DATA_DIR = Path(os.environ.get("S5_DATA_DIR",
                   str(PROJECT_ROOT / "data" / "scalper_parquet")))
INDICATOR_DIR = Path(os.environ.get("ASI_MC_DATA_DIR",
                     str(PROJECT_ROOT / "data" / "asi_mc_indicators")))

NEW_COLS = ["sb_a", "erp_a", "hh_asi", "hl_asi", "erp_p", "hh_price", "hl_price",
            "d_erp_p", "d_erp_a"]

# d_erp_p / d_erp_a: 1-hour rate-of-change in range position (12 M5 bars = 60 min)
# Answers: "is price losing/gaining range position?" — the velocity V3 is blind to.
# At 08:09 EUR/JPY: d_erp_p ≈ 0.56 - 1.05 = -0.49 (unambiguously reversing)
ERP_DELTA_WINDOW = 12  # bars


def load_s5_as_mid(pair: str):
    parquet = S5_DATA_DIR / f"{pair.replace('_', '')}_S5_BA.parquet"
    if not parquet.exists():
        print(f"    [SKIP] S5 parquet not found: {parquet}")
        return None
    df = pd.read_parquet(parquet, engine="pyarrow")
    ts = pd.to_datetime(df["timestamp"])
    half_spread = (df["ask_c"].values - df["bid_c"].values) / 2.0
    s5_df = pd.DataFrame({
        "o": df["bid_o"].values + half_spread,
        "h": df["bid_h"].values + half_spread,
        "l": df["bid_l"].values + half_spread,
        "c": df["bid_c"].values + half_spread,
    }, index=ts)
    del df
    return s5_df


def print_ic_report(features: dict, close: np.ndarray, pair: str):
    print(f"\n  IC Pre-Screening — {pair}")
    print(f"  {'Feature':<14}  {'IC':>8}  {'n_valid':>8}  {'|IC|>0.03':>10}")
    print(f"  {'-'*46}")
    kept = {}
    for name, arr in features.items():
        ic, n = compute_ic(arr, close, lag=1)
        passed = "PASS" if abs(ic) > 0.03 and n >= 1000 else "fail"
        if abs(ic) > 0.03 and n >= 1000:
            kept[name] = arr
        print(f"  {name:<14}  {ic:>8.4f}  {n:>8,}  {passed:>10}")
    if len(kept) >= 2:
        names = list(kept.keys())
        print(f"  Cross-correlations (>0.60 = redundant):")
        for i in range(len(names)):
            for j in range(i + 1, len(names)):
                r = compute_corr(kept[names[i]], kept[names[j]])
                flag = " REDUNDANT" if abs(r) > 0.60 else ""
                print(f"    {names[i]} x {names[j]}: {r:+.3f}{flag}")


def main():
    print("Export Swing Structure Indicators (curator-identical via SwingStructure class)")
    print(f"S5 source : {S5_DATA_DIR}")
    print(f"Indicators: {INDICATOR_DIR}")
    print()

    t_total = time.time()
    results_summary = []

    for pair in ALL_PAIR_NAMES:
        t0 = time.time()
        print(f"{pair}...", flush=True)

        ind_path = INDICATOR_DIR / f"{pair}_asi_mc.parquet"
        if not ind_path.exists():
            print(f"  [SKIP] No indicator parquet")
            continue

        existing = pd.read_parquet(ind_path, engine="pyarrow")

        if all(c in existing.columns for c in NEW_COLS):
            print(f"  [SKIP] Swing columns already present ({len(existing)} bars)")
            continue

        s5_df = load_s5_as_mid(pair)
        if s5_df is None:
            continue

        # Resample S5 → M5 OHLC
        m5 = s5_df.resample("5min").agg(
            {"o": "first", "h": "max", "l": "min", "c": "last"}
        ).dropna()
        n_m5 = min(len(m5), len(existing))
        if n_m5 < len(existing):
            print(f"  Aligning: {len(existing)} existing vs {len(m5)} M5 → {n_m5}")

        # Feed bars into SwingStructure — identical call pattern as live curator
        # Then read off the batch result for all bars at once.
        # The batch approach (compute_all_swing_features on full array) is
        # mathematically identical to feeding bars one-by-one and calling
        # compute() after each, but runs in O(N) instead of O(N²).
        # The curator also runs batch (full buffer recompute every M5 bar).
        sw = SwingStructure()

        print(f"  {n_m5:,} bars, running SwingStructure...", end=" ", flush=True)
        o = m5["o"].values[:n_m5].astype(np.float64)
        h = m5["h"].values[:n_m5].astype(np.float64)
        l = m5["l"].values[:n_m5].astype(np.float64)
        c = m5["c"].values[:n_m5].astype(np.float64)

        # Load all bars into the buffer (same as curator warmup)
        for i in range(n_m5):
            sw.append_m5(float(o[i]), float(h[i]), float(l[i]), float(c[i]))

        # Now use the shared batch function (same as SwingStructure.compute() internals)
        # to get the per-bar values for the full history
        from lib.swing_indicators import compute_all_swing_features, ffill_zero
        import numpy as _np
        from lib.asi_indicator import compute_asi

        o_arr = _np.array(sw.m5_o, dtype=_np.float64)
        h_arr = _np.array(sw.m5_h, dtype=_np.float64)
        l_arr = _np.array(sw.m5_l, dtype=_np.float64)
        c_arr = _np.array(sw.m5_c, dtype=_np.float64)
        asi = compute_asi(o_arr, h_arr, l_arr, c_arr, len(o_arr))
        feats = compute_all_swing_features(o_arr, h_arr, l_arr, c_arr, asi)

        sb_a     = ffill_zero(feats["sb_a"])[:n_m5]
        erp_a    = ffill_zero(feats["erp_a"])[:n_m5]
        hh_asi   = ffill_zero(feats["hh_asi"])[:n_m5]
        hl_asi   = ffill_zero(feats["hl_asi"])[:n_m5]
        erp_p    = ffill_zero(feats["erp_p"])[:n_m5]
        hh_price = ffill_zero(feats["hh_price"])[:n_m5]
        hl_price = ffill_zero(feats["hl_price"])[:n_m5]

        # Delta features: 1-hour rate-of-change in range position
        # d_erp_p[i] = erp_p[i] - erp_p[i-12]  (12 M5 bars = 60 min)
        # At reversal: d_erp_p ≈ -0.49 (was >1.0, now 0.56) — unambiguous signal
        W = ERP_DELTA_WINDOW
        d_erp_p = _np.zeros(n_m5, dtype=_np.float64)
        d_erp_a = _np.zeros(n_m5, dtype=_np.float64)
        d_erp_p[W:] = erp_p[W:] - erp_p[:n_m5 - W]
        d_erp_a[W:] = erp_a[W:] - erp_a[:n_m5 - W]

        print("done")
        n_nan_erp_a = int(_np.isnan(feats["erp_a"]).sum())
        n_nan_erp_p = int(_np.isnan(feats["erp_p"]).sum())
        print(f"  ERP_A NaN startup: {n_nan_erp_a} ({n_nan_erp_a/n_m5*100:.1f}%)")
        print(f"  ERP_P NaN startup: {n_nan_erp_p} ({n_nan_erp_p/n_m5*100:.1f}%)")
        print(f"  SB_A dist: +1={_np.sum(sb_a>0.4):,}  0={_np.sum(sb_a==0):,}  -1={_np.sum(sb_a<-0.4):,}")
        print(f"  d_erp_p range: [{d_erp_p[W:].min():.3f}, {d_erp_p[W:].max():.3f}]  "
              f"std={d_erp_p[W:].std():.3f}")
        print(f"  d_erp_a range: [{d_erp_a[W:].min():.3f}, {d_erp_a[W:].max():.3f}]  "
              f"std={d_erp_a[W:].std():.3f}")

        # IC pre-screening
        mid_close = existing["mid_close"].values[:n_m5] if "mid_close" in existing.columns else c
        print_ic_report({
            "sb_a": sb_a, "erp_a": erp_a, "hh_asi": hh_asi, "hl_asi": hl_asi,
            "erp_p": erp_p, "hh_price": hh_price, "hl_price": hl_price,
            "d_erp_p": d_erp_p, "d_erp_a": d_erp_a,
        }, mid_close.astype(_np.float64), pair)

        # Merge into existing parquet
        existing = existing.iloc[:n_m5].copy()
        existing["sb_a"]      = sb_a
        existing["erp_a"]     = erp_a
        existing["hh_asi"]    = hh_asi
        existing["hl_asi"]    = hl_asi
        existing["erp_p"]     = erp_p
        existing["hh_price"]  = hh_price
        existing["hl_price"]  = hl_price
        existing["d_erp_p"]   = d_erp_p
        existing["d_erp_a"]   = d_erp_a

        existing.to_parquet(ind_path, index=False, engine="pyarrow")
        elapsed = time.time() - t0
        print(f"  Saved: {ind_path.name} ({len(existing.columns)} cols, {elapsed:.1f}s)")
        results_summary.append((pair, n_m5, elapsed))
        del s5_df, m5, existing, sw
        gc.collect()

    total = time.time() - t_total
    print(f"\n{'='*60}")
    print(f"Export complete in {total:.0f}s ({total/60:.1f} min)")
    print(f"{'Pair':<12}  {'Bars':>8}  {'Time':>6}")
    for pair, n, t in results_summary:
        print(f"  {pair:<10}  {n:>8,}  {t:>5.1f}s")
    print(f"\nNew columns: {NEW_COLS}")
    print(f"\nIC gate:   |IC| > 0.03 = real signal")
    print(f"Corr gate: max_corr < 0.60 = non-redundant")
    print(f"\nNext: run train_swingdim.py --mode E1|E2|E3")


if __name__ == "__main__":
    main()
