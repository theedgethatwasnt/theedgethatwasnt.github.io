from pathlib import Path

import cma
import numpy as np
import pandas as pd
from numba import njit

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from research.experiments.elementary_ma.features import ARM_FEATURES

DATA_DIR = Path(os.environ.get(
    "CMA5IN_DATA_DIR", str(PROJECT_ROOT / "data" / "unified_indicators")))
FEAT_DIR = Path(os.environ.get(
    "ELEMENTARY_FEATURES_DIR",
    str(PROJECT_ROOT / "data" / "elementary_ma_features")))
RESULTS_DIR = SCRIPT_DIR / "results"
PROGRESS_DIR = RESULTS_DIR / "progress"
LIVE_RESULTS = RESULTS_DIR / "live_results.jsonl"

PAIR_PIP = {
    "EUR_JPY": 0.01, "USD_JPY": 0.01, "GBP_JPY": 0.01, "AUD_JPY": 0.01,
    "CAD_JPY": 0.01, "CHF_JPY": 0.01, "NZD_JPY": 0.01,
    "EUR_USD": 0.0001, "GBP_USD": 0.0001, "AUD_USD": 0.0001,
    "NZD_USD": 0.0001, "EUR_GBP": 0.0001,
}
PAIR_SPREAD = {
    "EUR_JPY": 2.3, "USD_JPY": 1.7, "GBP_JPY": 3.3, "AUD_JPY": 2.1,
    "CAD_JPY": 2.3, "CHF_JPY": 3.5, "NZD_JPY": 2.7,
    "EUR_USD": 1.6, "GBP_USD": 1.9, "AUD_USD": 1.3,
    "NZD_USD": 1.5, "EUR_GBP": 1.4,
}

N_HID = 8
N_OUT = 3
N_ACTS = 9
ACT_NAMES = ["tanh", "sin", "cos", "gauss", "sech", "dog", "gabor", "sinc", "morlet"]


def compute_layout(n_in):
    w1_end = n_in * N_HID
    b1_end = w1_end + N_HID
    w2_end = b1_end + N_HID * N_OUT
    b2_end = w2_end + N_OUT
    act_end = b2_end + N_HID
    scale_end = act_end + N_HID
    return dict(w1_end=w1_end, b1_end=b1_end, w2_end=w2_end, b2_end=b2_end,
                act_end=act_end, scale_end=scale_end, n_params=scale_end)


@njit(cache=True, inline="always")
def activate(z, act_id):
    if act_id == 0: return np.tanh(z)
    elif act_id == 1: return np.sin(z)
    elif act_id == 2: return np.cos(z)
    elif act_id == 3: return np.exp(-z * z)
    elif act_id == 4:
        zc = min(max(z, -50.0), 50.0); return 1.0 / np.cosh(zc)
    elif act_id == 5: return np.exp(-z * z / 2.0) - 0.5 * np.exp(-z * z / 8.0)
    elif act_id == 6: return np.exp(-2.0 * z * z) * np.cos(2.0 * np.pi * z)
    elif act_id == 7:
        if z > 1e-7 or z < -1e-7: return np.sin(np.pi * z) / (np.pi * z)
        return 1.0
    else: return np.sin(z) * np.exp(-z * z / 2.0)


@njit(cache=True, inline="always")
def decode_act(gene):
    g = gene - np.floor(gene)
    aid = int(g * N_ACTS)
    if aid < 0: aid = 0
    if aid >= N_ACTS: aid = N_ACTS - 1
    return aid


@njit(cache=True, inline="always")
def decode_scale(gene):
    s = 1.0 / (1.0 + np.exp(-gene))
    return 0.1 + s * 4.9


@njit(cache=True)
def compute_m5_slope(closes, lookback=12):
    n = len(closes)
    out = np.zeros(n)
    hp = np.pi / 2.0
    for i in range(lookback, n):
        x_mean = (lookback - 1) / 2.0
        y_mean = 0.0
        for k in range(lookback):
            y_mean += closes[i - lookback + 1 + k]
        y_mean /= lookback
        num = 0.0; den = 0.0
        ymin = closes[i - lookback + 1]; ymax = ymin
        for k in range(lookback):
            y = closes[i - lookback + 1 + k]
            xd = k - x_mean
            num += xd * (y - y_mean)
            den += xd * xd
            if y < ymin: ymin = y
            if y > ymax: ymax = y
        if den > 0:
            slope = num / den
            rng = ymax - ymin
            out[i] = np.arctan((slope / rng * 3.0) if rng > 0 else 0.0) / hp
    return out


@njit(cache=True)
def simulate_chunk(
    m5_slope, h1_slope, mid_close, extra_feats,
    pip, spread_pips, max_hold,
    weights, n_in, w1_end, b1_end, w2_end, b2_end, act_end, scale_end,
    chunk_start, chunk_end, n_extra,
):
    """Walk bars; return (n_trades, total_pnl, n_long, n_short)."""
    start_bar = max(chunk_start + 12, 12)
    end_bar = min(chunk_end, len(mid_close) - 1)
    n_capacity = end_bar - start_bar + 1
    if n_capacity <= 0:
        return 0, 0.0, 0, 0

    pnls = np.zeros(n_capacity)
    n_trades = 0; n_long = 0; n_short = 0
    position = 0; entry_price = 0.0; entry_bar = 0
    upnl_pips = 0.0; mae_pips = 0.0; mfe_pips = 0.0

    x = np.zeros(n_in)
    h = np.zeros(N_HID)
    act_ids = np.zeros(N_HID, dtype=np.int64)
    scales = np.zeros(N_HID)
    for j in range(N_HID):
        act_ids[j] = decode_act(weights[b2_end + j])
        scales[j] = decode_scale(weights[act_end + j])

    for i in range(start_bar, end_bar):
        if position != 0:
            upnl_pips = (mid_close[i] - entry_price) / pip * position
            if -upnl_pips > mae_pips: mae_pips = -upnl_pips
            if upnl_pips > mfe_pips: mfe_pips = upnl_pips
        else:
            upnl_pips = 0.0; mae_pips = 0.0; mfe_pips = 0.0

        x[0] = m5_slope[i]
        x[1] = h1_slope[i]
        x[2] = np.tanh(upnl_pips / 20.0)
        x[3] = np.tanh(mae_pips / 20.0)
        x[4] = np.tanh(mfe_pips / 20.0)
        for k in range(n_extra):
            x[5 + k] = extra_feats[k, i]

        for j in range(N_HID):
            z = weights[w1_end + j]
            for k in range(n_in):
                z += weights[j * n_in + k] * x[k]
            h[j] = activate(scales[j] * z, act_ids[j])

        out_buy = weights[w2_end + 0]
        out_sell = weights[w2_end + 1]
        out_flat = weights[w2_end + 2]
        for j in range(N_HID):
            out_buy += weights[b1_end + 0 * N_HID + j] * h[j]
            out_sell += weights[b1_end + 1 * N_HID + j] * h[j]
            out_flat += weights[b1_end + 2 * N_HID + j] * h[j]

        if out_buy >= out_sell and out_buy >= out_flat:
            action = 1
        elif out_sell >= out_buy and out_sell >= out_flat:
            action = 2
        else:
            action = 0

        if position != 0 and (i - entry_bar) >= max_hold:
            pnl = (mid_close[i] - entry_price) / pip * position
            if n_trades < n_capacity:
                pnls[n_trades] = pnl
                if position > 0: n_long += 1
                else: n_short += 1
                n_trades += 1
            position = 0; entry_price = 0.0; mae_pips = 0.0; mfe_pips = 0.0

        if position == 0:
            if action == 1:
                position = 1
                entry_price = mid_close[i] + spread_pips * pip
                entry_bar = i; mae_pips = spread_pips; mfe_pips = 0.0
            elif action == 2:
                position = -1
                entry_price = mid_close[i] - spread_pips * pip
                entry_bar = i; mae_pips = spread_pips; mfe_pips = 0.0
        else:
            close_now = False; new_pos = 0
            if action == 0:
                close_now = True
            elif position == 1 and action == 2:
                close_now = True; new_pos = -1
            elif position == -1 and action == 1:
                close_now = True; new_pos = 1
            if close_now:
                pnl = (mid_close[i] - entry_price) / pip * position
                if n_trades < n_capacity:
                    pnls[n_trades] = pnl
                    if position > 0: n_long += 1
                    else: n_short += 1
                    n_trades += 1
                position = new_pos
                if new_pos == 1:
                    entry_price = mid_close[i] + spread_pips * pip
                    entry_bar = i; mae_pips = spread_pips; mfe_pips = 0.0
                elif new_pos == -1:
                    entry_price = mid_close[i] - spread_pips * pip
                    entry_bar = i; mae_pips = spread_pips; mfe_pips = 0.0
                else:
                    entry_price = 0.0

    if position != 0 and end_bar > start_bar:
        pnl = (mid_close[end_bar - 1] - entry_price) / pip * position
        if n_trades < n_capacity:
            pnls[n_trades] = pnl
            if position > 0: n_long += 1
            else: n_short += 1
            n_trades += 1

    if n_trades < 1:
        return 0, 0.0, 0, 0
    total = 0.0
    for k in range(n_trades):
        total += pnls[k]
    return n_trades, total, n_long, n_short


def fitness(weights, m5, h1, mid, extra, pip, spread, max_hold,
            n_chunks, min_dir_ratio, layout, n_in, n_extra):
    ly = layout
    n_bars = len(mid)
    total_long = 0; total_short = 0; total_trades = 0; total_pnl = 0.0
    chunk_pps = []; losing_chunk_loss = 0.0

    for ci in range(n_chunks):
        c_start = int(n_bars * ci / n_chunks)
        c_end = int(n_bars * (ci + 1) / n_chunks)
        nt, pnl, nl, ns = simulate_chunk(
            m5, h1, mid, extra, pip, spread, max_hold, weights,
            n_in, ly["w1_end"], ly["b1_end"], ly["w2_end"],
            ly["b2_end"], ly["act_end"], ly["scale_end"],
            c_start, c_end, n_extra)
        total_long += nl; total_short += ns; total_trades += nt; total_pnl += pnl
        n_days = (c_end - c_start) / 288.0
        pps = pnl / n_days if n_days > 0 else 0.0
        chunk_pps.append(pps)
        if pps < 0: losing_chunk_loss += -pps

    total_days = n_bars / 288.0
    base_pps = total_pnl / total_days if total_days > 0 else 0.0
    if total_trades == 0:
        return 500.0 - base_pps
    dir_ratio = min(total_long, total_short) / total_trades
    asym_penalty = (1.0 - 2.0 * dir_ratio) * 50.0
    activity_penalty = max(0.0, 30.0 - total_trades) * 2.0
    losing_pen = losing_chunk_loss * 2.0
    all_profitable = all(p > 0 for p in chunk_pps)
    if all_profitable and dir_ratio >= min_dir_ratio:
        score = min(chunk_pps) - asym_penalty
    else:
        score = base_pps - asym_penalty - activity_penalty - losing_pen
    return -score


def eval_oos(weights, m5, h1, mid, extra, pip, spread, max_hold, layout,
             n_in, n_extra):
    ly = layout
    nt, pnl, nl, ns = simulate_chunk(
        m5, h1, mid, extra, pip, spread, max_hold, weights,
        n_in, ly["w1_end"], ly["b1_end"], ly["w2_end"],
        ly["b2_end"], ly["act_end"], ly["scale_end"],
        0, len(mid), n_extra)
    n_days = len(mid) / 288.0
    return {
        "n_trades": int(nt),
        "total_pnl": round(float(pnl), 1),
        "pips_per_day": round(float(pnl) / max(n_days, 1), 2),
        "n_long": int(nl), "n_short": int(ns),
        "dir_ratio": round(min(nl, ns) / max(nt, 1), 3),
    }


_W = {}


def _worker_init(m5, h1, mid, extra, pip, spread, max_hold,
                 n_chunks, min_dir, layout, n_in, n_extra):
    _W.update(m5=m5, h1=h1, mid=mid, extra=extra, pip=pip, spread=spread,
              max_hold=max_hold, n_chunks=n_chunks, min_dir=min_dir,
              layout=layout, n_in=n_in, n_extra=n_extra)


def _worker_fit(vec):
    return fitness(vec, _W["m5"], _W["h1"], _W["mid"], _W["extra"],
                   _W["pip"], _W["spread"], _W["max_hold"],
                   _W["n_chunks"], _W["min_dir"], _W["layout"],
                   _W["n_in"], _W["n_extra"])


def load_features_for_arm(pair: str, arm: str) -> np.ndarray:
    """Return extra features as shape (n_extra, n_bars) ready for numba."""
    feat_path = FEAT_DIR / f"{pair}_features.npz"
    if not feat_path.exists():
        raise FileNotFoundError(f"Precompute first: {feat_path}")
    data = np.load(feat_path)
    feat_names = ARM_FEATURES[arm]
    arrays = [data[name].astype(np.float64) for name in feat_names]
    # NaN→0 (training runs skip warmup region anyway; simulate_chunk starts at bar 12)
    arrays = [np.nan_to_num(a, nan=0.0) for a in arrays]
    return np.ascontiguousarray(np.array(arrays))  # shape (n_extra, n_bars)


def append_live_result(result_dict):
    """Append one JSON line to live_results.jsonl atomically (one process per line)."""
    LIVE_RESULTS.parent.mkdir(parents=True, exist_ok=True)
    with open(LIVE_RESULTS, "a") as f:
        f.write(json.dumps(result_dict, default=str) + "\n")


def write_progress(tag: str, gen: int, best_fit: float, sigma: float):
    """Append per-generation state to the progress log for this run."""
    PROGRESS_DIR.mkdir(parents=True, exist_ok=True)
    log = PROGRESS_DIR / f"{tag}.log"
    with open(log, "a") as f:
        f.write(f"{gen}\t{best_fit:.4f}\t{sigma:.5f}\t{time.time():.0f}\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--pair", required=True)
    parser.add_argument("--arm", required=True, choices=list(ARM_FEATURES.keys()))
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--gens", type=int, default=200)
    parser.add_argument("--popsize", type=int, default=24)
    parser.add_argument("--sigma0", type=float, default=0.5)
    parser.add_argument("--max-hold", type=int, default=200)
    parser.add_argument("--n-chunks", type=int, default=5)
    parser.add_argument("--min-dir-ratio", type=float, default=0.15)
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()

    np.random.seed(args.seed)
    extra_feats = load_features_for_arm(args.pair, args.arm)
    n_extra = extra_feats.shape[0]
    n_in = 5 + n_extra
    layout = compute_layout(n_in)

    pair = args.pair
    pip = PAIR_PIP[pair]
    spread = PAIR_SPREAD[pair]
    tag = f"{args.arm}_{pair}_s{args.seed}"

    print(f"{'=' * 70}")
    print(f"  ELEMENTARY-MA: {pair} | arm={args.arm}")
    print(f"  Topology: {n_in}→{N_HID}→{N_OUT}  ({layout['n_params']} params)")
    print(f"  Features: baseline5 + {ARM_FEATURES[args.arm]}")
    print(f"  Seed={args.seed} pop={args.popsize} σ0={args.sigma0} gens={args.gens}")
    print(f"{'=' * 70}")

    path = DATA_DIR / f"{pair}_unified.parquet"
    df = pd.read_parquet(path, engine="pyarrow")
    mid = df["mid_close"].values.astype(np.float64)
    h1_slope_full = df["h1_slope"].values.astype(np.float64)
    m5_slope_full = compute_m5_slope(mid, lookback=12)
    del df; gc.collect()

    # Guard: feature length must match
    if extra_feats.shape[1] != len(mid):
        raise RuntimeError(
            f"feature length {extra_feats.shape[1]} != mid length {len(mid)}")

    n = len(mid)
    split = int(n * 0.7)
    mid_is, mid_oos = mid[:split], mid[split:]
    h1_is, h1_oos = h1_slope_full[:split], h1_slope_full[split:]
    m5_is, m5_oos = m5_slope_full[:split], m5_slope_full[split:]
    ef_is = np.ascontiguousarray(extra_feats[:, :split])
    ef_oos = np.ascontiguousarray(extra_feats[:, split:])

    print(f"Data: {n:,} M5 bars | IS: {split:,} | OOS: {n - split:,}")
    print("JIT warming up...")
    warm = np.zeros(layout["n_params"])
    simulate_chunk(m5_is[:200], h1_is[:200], mid_is[:200], ef_is[:, :200],
                   pip, spread, 50, warm, n_in,
                   layout["w1_end"], layout["b1_end"], layout["w2_end"],
                   layout["b2_end"], layout["act_end"], layout["scale_end"],
                   0, 200, n_extra)
    print("  warm.")

    x0 = np.random.randn(layout["n_params"]) * 0.3
    x0[layout["b2_end"]:layout["act_end"]] = np.random.uniform(0.0, 1.0, N_HID)
    x0[layout["act_end"]:layout["scale_end"]] = 0.0

    opts = {
        "popsize": args.popsize, "seed": args.seed, "verbose": -9,
        "tolx": 1e-9, "tolfun": 1e-3, "tolfunhist": 1e-3,
        "tolflatfitness": 50, "maxiter": args.gens,
    }
    es = cma.CMAEvolutionStrategy(x0, args.sigma0, opts)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    PROGRESS_DIR.mkdir(parents=True, exist_ok=True)

    best_fit = 1e18
    best_vec = None
    t0 = time.time()

    init_args = (m5_is, h1_is, mid_is, ef_is, pip, spread, args.max_hold,
                 args.n_chunks, args.min_dir_ratio, layout, n_in, n_extra)
    pool = ProcessPoolExecutor(
        max_workers=args.workers, initializer=_worker_init, initargs=init_args)

    try:
        gen = 0
        while not es.stop():
            candidates = es.ask()
            fitnesses = list(pool.map(_worker_fit, candidates))
            es.tell(candidates, fitnesses)
            gen_min = min(fitnesses)
            if gen_min < best_fit:
                best_fit = gen_min
                best_idx = fitnesses.index(gen_min)
                best_vec = np.array(candidates[best_idx])
            # Stream every gen
            write_progress(tag, gen, best_fit, es.sigma)
            if gen % 10 == 0:
                print(f"  Gen {gen:>3}: fit={best_fit:>10.2f}  "
                      f"σ={es.sigma:.4f}  {time.time() - t0:.0f}s")
            gen += 1
            if gen >= args.gens:
                break
    finally:
        pool.shutdown(wait=True)

    elapsed = time.time() - t0
    if best_vec is None:
        print(f"No candidates in {gen} gens.")
        sys.exit(2)

    is_full = eval_oos(best_vec, m5_is, h1_is, mid_is, ef_is, pip, spread,
                       args.max_hold, layout, n_in, n_extra)
    oos = eval_oos(best_vec, m5_oos, h1_oos, mid_oos, ef_oos, pip, spread,
                   args.max_hold, layout, n_in, n_extra)
    print(f"\nIS:  {is_full}")
    print(f"OOS: {oos}")

    chosen_acts = [ACT_NAMES[decode_act(best_vec[layout["b2_end"] + j])]
                   for j in range(N_HID)]

    # Save full weights
    result = {
        "weights": best_vec, "n_in": n_in, "n_extra": n_extra,
        "layout": layout, "pair": pair, "seed": args.seed, "arm": args.arm,
        "best_fit": float(best_fit), "is_full": is_full, "oos": oos,
        "hidden_activations": chosen_acts, "elapsed_s": round(elapsed, 1),
        "args": vars(args),
    }
    final_path = RESULTS_DIR / f"{tag}_best.pkl"
    with open(final_path, "wb") as f:
        pickle.dump(result, f)

    # Streaming line (one per completion)
    summary = {
        "ts": time.strftime("%Y-%m-%d %H:%M:%S"),
        "tag": tag, "arm": args.arm, "pair": pair, "seed": args.seed,
        "oos_pps": oos["pips_per_day"], "is_pps": is_full["pips_per_day"],
        "oos_trades": oos["n_trades"], "is_trades": is_full["n_trades"],
        "oos_dir_ratio": oos["dir_ratio"],
        "best_fit": float(best_fit), "elapsed_s": round(elapsed, 1),
        "hidden_activations": chosen_acts,
    }
    append_live_result(summary)
    print(f"\nSaved: {final_path.name}")
    print(f"Live: {LIVE_RESULTS.name}")


if __name__ == "__main__":
    main()
