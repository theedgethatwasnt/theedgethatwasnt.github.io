#!/usr/bin/env python3
"""Elementary-MA CMA-ES trainer (streaming).

Adapts train_pinn_cma.py. Five arms: E-atan, E-pz-norm, E-pz-rank, E-mom, E-all.

Streaming results
-----------------
- After every run (one pair × seed × arm), appends a JSON line to
  ``live_results.jsonl`` in the results dir — tail to see completions live.
- Per-generation best fitness is appended to
  ``progress/{arm}_{pair}_s{seed}.log`` so you can ``tail -f`` the CMA state of
  an individual run while it's executing.

Usage
-----
    python3 train_elementary_cma.py --pair EUR_JPY --arm E-atan --seed 42 \
        [--gens 200] [--popsize 24] [--workers 14]

Orchestrate multiple runs with ``run_all.sh`` (generated by deploy script).
"""
